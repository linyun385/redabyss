def main():
    jobs = json.loads(SRC.read_text(encoding='utf-8'))
    out = []
    for j in jobs:
        p = j['prompt']
        for old, new in FIX.get(j['id'], []):
            if old not in p:
                print('!! 替换未命中:', j['id'])
                print('   待找:', old[:40])
            p = p.replace(old, new)
        out.append({'id': j['id'].replace('_zh3_', '_zh3b_'), 'prompt': p})
    DST.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding='utf-8')
    print('写出', DST.name, len(out), '条；改过', len(FIX), '条')
    return 0


