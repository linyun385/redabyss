def main():
    made = []
    for i, (title, problem, goal, steps, forbid, accept, deliver) in enumerate(T):
        n = START + i
        body = ['# T%d %s' % (n, title), '', '## 实测问题', problem, '', '## 目标', goal, '',
                '## 做法（按优先级）']
        body += ['%d. %s' % (k, s) for k, s in enumerate(steps, 1)]
        body += ['', '## 禁止', forbid, '', '## 验收', '| # | 指标 | 门槛 |', '|---|---|---|']
        body += ['| %d | %s | %s |' % (k, a, b) for k, (a, b) in enumerate(accept, 1)]
        body += ['', '## 交付', deliver, '']
        (TASKS / ('T%d.md' % n)).write_text('\n'.join(body), encoding='utf-8')
        made.append({'t': n, 'title': title, 'deliver': deliver})

    qp = TASKS / 'queue.json'
    q = json.loads(qp.read_text(encoding='utf-8'))
    have = {x['t'] for x in q['queue']}
    q['queue'] += [x for x in made if x['t'] not in have]
    q['end'] = q['queue'][-1]['t']
    q['count'] = len(q['queue'])
    qp.write_text(json.dumps(q, ensure_ascii=False, indent=1), encoding='utf-8')
    print('补 T%d–T%d 共 %d 个' % (START, START + len(made) - 1, len(made)))
    print('队列现在 T%d–T%d，共 %d 个' % (q['start'], q['end'], q['count']))
    return 0


if __name__ == '__main__':
    sys.exit(main())
