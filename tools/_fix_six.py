def main():
    rows = json.loads(P.read_text(encoding='utf-8'))
    bak = P.with_suffix('.bak3.json')
    if not bak.exists():
        bak.write_text(P.read_text(encoding='utf-8'), encoding='utf-8')
    hit = 0
    jobs = []
    for r in rows:
        if r['id'] not in NEW:
            continue
        old = r['prompt']
        i = old.find(MARK)
        if i < 0:
            print('!! %s 找不到标记，跳过' % r['id'])
            continue
        r['prompt'] = NEW[r['id']] + old[i:]
        hit += 1
        print('%-10s 主体 %d → %d 字' % (r['id'], i, len(NEW[r['id']])))
        jobs.append({'id': r['id'], 'prompt': r['prompt']})
    P.write_text(json.dumps(rows, ensure_ascii=False, indent=1), encoding='utf-8')
    out = GAME / 'data' / 'jobs_six.json'
    out.write_text(json.dumps(jobs, ensure_ascii=False, indent=1), encoding='utf-8')
    print('改 %d 条，写出 %s' % (hit, out.name))
    return 0


if __name__ == '__main__':
    sys.exit(main())
